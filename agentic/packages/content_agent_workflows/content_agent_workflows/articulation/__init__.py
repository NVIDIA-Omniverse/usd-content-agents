def __getattr__(name: str) -> Any:
    """Load verified-operation projectors without making CLI startup eager."""

    if name in _ASSET_LEAF_ADAPTER_EXPORTS:
        from . import asset_leaf_adapter

        return getattr(asset_leaf_adapter, name)
    if name in _VERIFIED_OPERATION_EXPORTS:
        from . import verified_operations

        return getattr(verified_operations, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


