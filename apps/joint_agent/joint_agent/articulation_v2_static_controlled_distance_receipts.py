class ArticulationV2StaticControlledDistanceReadbackReceiptV2(_ReceiptModel):
    schema_version: Literal[
        "joint-agent-articulation-v2-static-controlled-distance-readback-v2"
    ]
    representation: Literal["prismatic_axial_interval_drive_body1_to_body0_v2"]
    binding: ArticulationV2StaticControlledDistanceEvidenceBindingV2
    stage: ArticulationV2StaticControlledDistanceReceiptStageV2
    status: Literal["pass", "fail"]
    authoring_receipt_sha256: str
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    selector_semantics: ArticulationV2ControlledDistanceSelectorSemanticsV2
    expected: ControlledDistanceContractV2
    source_attachments: ExplicitAttachmentFramesV2
    observed: ControlledDistanceStageReadbackV2
    source_readback_protocol: ControlledDistanceV2SourceReadbackProtocol
    checks: ArticulationV2StaticControlledDistanceComparisonChecksV2

    @field_validator("authoring_receipt_sha256")
    @classmethod
    def _authoring_hash(cls, value: str) -> str:
        return _sha256(value, "authoring_receipt_sha256")

    @model_validator(mode="after")
    def _saved_stage_comparison(
        self,
    ) -> ArticulationV2StaticControlledDistanceReadbackReceiptV2:
        if self.stage.plan.stage != "readback":
            raise ValueError("V2 readback receipt requires the readback stage")
        _require_same_representation(self)
        _require_generated_file_matches_identities(
            self.generated_file, self.generated_identities
        )
        if self.selector_semantics.controlled_distance_contract != self.expected:
            raise ValueError(
                "V2 readback expected contract differs from selector semantics"
            )
        admitted_attachments = _controlled_distance_source_attachments(
            self.binding.run.selector.source_semantic_preimage
        )
        if self.source_attachments != admitted_attachments:
            raise ValueError(
                "V2 readback source attachments differ from selector admission"
            )
        expected_checks = articulation_v2_static_controlled_distance_comparison_checks(
            self.expected,
            self.observed,
            source_attachments=self.source_attachments,
        )
        if self.checks != expected_checks:
            raise ValueError("V2 readback checks differ from substantive comparison")
        if self.status != ("pass" if expected_checks.passed else "fail"):
            raise ValueError("V2 readback status differs from substantive comparison")
        return self


