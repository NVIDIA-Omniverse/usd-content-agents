    @model_validator(mode="after")
    def _failure_stage(
        self,
    ) -> ArticulationV2StaticControlledDistanceGate3FailureReceiptV2:
        stage = self.stage.plan.stage
        if stage not in {"gate3a", "gate3b"}:
            raise ValueError("V2 Gate 3 failure requires a Gate 3 stage")
        _require_same_representation(self)
        _require_generated_file_matches_identities(
            self.generated_file, self.generated_identities
        )
        if (
            self.failure_code
            != f"articulation_v2_static_{stage}_report_missing_after_exit"
        ):
            raise ValueError("V2 Gate 3 failure code differs from stage")
