def _project_attachments(
    attachments: ExplicitAttachmentFramesV2,
    *,
    meters_per_unit: float,
) -> ExplicitAttachmentFramesV2:
    if not math.isfinite(meters_per_unit) or meters_per_unit <= 0.0:
        raise ValueError("V2 saved readback stage scale must be finite and positive")

    def project(value: float, units: float) -> float:
        try:
            result = struct.unpack("!f", struct.pack("!f", value / units))[0] * units
        except (OverflowError, struct.error) as exc:
            raise ValueError("V2 attachment is not representable as binary32") from exc
        if not math.isfinite(result):
            raise ValueError("V2 attachment is not finite after binary32 projection")
        return 0.0 if result == 0.0 else result

    def frame(value: AttachmentFrameV2) -> AttachmentFrameV2:
        return AttachmentFrameV2(
            position_meters=tuple(
                project(item, meters_per_unit) for item in value.position_meters
            ),
            orientation_wxyz=tuple(
                project(item, 1.0) for item in value.orientation_wxyz
            ),
        )

    return ExplicitAttachmentFramesV2(
        kind="explicit",
        body0=frame(attachments.body0),
        body1=frame(attachments.body1),
    )


_ModelT = TypeVar("_ModelT", bound=BaseModel)


def _canonical(value: _ModelT, model: type[_ModelT]) -> bytes:
    if type(value) is not model:
        raise TypeError(f"value must be an exact {model.__name__}")
    adapter = TypeAdapter(model)
    payload = json.dumps(
        adapter.dump_python(value, mode="json"),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")
    validated = adapter.validate_json(payload, strict=True)
    return json.dumps(
        adapter.dump_python(validated, mode="json"),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


