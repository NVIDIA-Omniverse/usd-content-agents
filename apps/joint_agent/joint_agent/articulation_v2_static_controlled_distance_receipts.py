    schema_version: Literal[
        "joint-agent-articulation-v2-static-controlled-distance-gate3-claim-v2"
    ]
    representation: Literal["prismatic_axial_interval_drive_body1_to_body0_v2"]
    binding: ArticulationV2StaticControlledDistanceEvidenceBindingV2
    stage: ArticulationV2StaticControlledDistanceReceiptStageV2
    status: ReceiptStatus
    readback_receipt_sha256: str
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    raw_report: StaticReceiptFileV1
    stdout_log: StaticReceiptFileV1
    stderr_log: StaticReceiptFileV1
    support_evidence: StaticReceiptFileV1 | None = None

    @field_validator("readback_receipt_sha256")
    @classmethod
    def _readback_hash(cls, value: str) -> str:
        return _sha256(value, "readback_receipt_sha256")

    @model_validator(mode="after")
    def _gate3_stage(self) -> ArticulationV2StaticControlledDistanceGate3ClaimV2:
        stage = self.stage.plan.stage
        if stage not in {"gate3a", "gate3b"}:
            raise ValueError("V2 Gate 3 claim requires gate3a or gate3b")
        if self.raw_report.path != f"reports/{stage}.json":
            raise ValueError("V2 Gate 3 report path is unadmitted")
        if self.stdout_log.path != f"logs/{stage}.stdout.json":
            raise ValueError("V2 Gate 3 stdout path is unadmitted")
        if self.stderr_log.path != f"logs/{stage}.stderr.json":
            raise ValueError("V2 Gate 3 stderr path is unadmitted")
        if stage == "gate3a" and self.support_evidence is not None:
            raise ValueError("V2 Gate 3A cannot carry Gate 3B support")
        if stage == "gate3b" and (
            self.support_evidence is None
            or self.support_evidence.path != STATIC_EVIDENCE_GATE3B_SUPPORT_PATH
        ):
            raise ValueError("V2 Gate 3B requires support evidence")
        _require_generated_file_matches_identities(
            self.generated_file, self.generated_identities
        )
        _require_same_representation(self)
        return self


