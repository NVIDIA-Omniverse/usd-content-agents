def validate_articulation_v2_static_controlled_distance_result_bundle(
    loaded: LoadedCapabilityManifest,
    plan: ArticulationV2StaticControlledDistanceRunPlanV2,
    intake: ArticulationV2StaticControlledDistanceIntakeV2,
    bundle: ArticulationV2StaticControlledDistanceResultBundleV2,
) -> None:
    plan = _revalidate_articulation_v2_static_controlled_distance_run_plan(plan)
    intake = _revalidate_articulation_v2_static_controlled_distance_intake(intake)
    bundle = _revalidate_bundle(bundle)
    validate_articulation_v2_static_controlled_distance_intake(loaded, plan, intake)
    expected_binding = _binding(plan, intake)
    receipts = (
        bundle.adoption,
        bundle.authoring,
        bundle.readback,
        bundle.gate3a,
        bundle.gate3b,
    )
    if any(item.binding != expected_binding for item in receipts):
        raise CapabilityManifestError(
            "V2 bundle substitutes run-plan, intake, or source identity"
        )
    for receipt, stage in zip(receipts, plan.stages.ordered(), strict=True):
        if cast(Any, receipt).stage.plan != stage:
            raise CapabilityManifestError(f"V2 bundle substitutes {stage.stage} stage")
    if bundle.adoption.contract_file != StaticReceiptFileV1(
        path=intake.contract_uri,
        size_bytes=intake.contract_size_bytes,
        sha256=intake.contract_sha256,
    ):
        raise CapabilityManifestError("V2 adoption differs from exact intake contract")
    if (
        bundle.adoption.selector_semantics_sha256
        != articulation_v2_controlled_distance_selector_semantics_sha256(
            intake.contract_semantics
        )
    ):
        raise CapabilityManifestError(
            "V2 adoption semantic identity differs from intake"
        )
    if (
        bundle.readback.selector_semantics != intake.contract_semantics
        or bundle.readback.expected
        != intake.contract_semantics.controlled_distance_contract
    ):
        raise CapabilityManifestError("V2 saved readback differs from intake semantics")
    generated = bundle.authoring.generated_identities
    if generated is None or generated.authorer.uri != plan.output.output_key:
        raise CapabilityManifestError("V2 authoring differs from planned output")


def validate_articulation_v2_static_controlled_distance_completion(
    loaded: LoadedCapabilityManifest,
    plan: ArticulationV2StaticControlledDistanceRunPlanV2,
    intake: ArticulationV2StaticControlledDistanceIntakeV2,
    bundle: ArticulationV2StaticControlledDistanceResultBundleV2,
    completion: ArticulationV2StaticControlledDistanceCompletionReceiptV2,
) -> None:
    completion = _revalidate_completion(completion)
    validate_articulation_v2_static_controlled_distance_result_bundle(
        loaded, plan, intake, bundle
    )
    if completion.binding != _binding(plan, intake):
        raise CapabilityManifestError("V2 completion substitutes run identity")
    if completion.evidence_paths != plan.evidence_paths:
        raise CapabilityManifestError("V2 completion substitutes evidence paths")
    if (
        completion.generated_identities != bundle.authoring.generated_identities
        or completion.generated_file != bundle.authoring.generated_file
    ):
        raise CapabilityManifestError("V2 completion substitutes generated identities")
    expected = _expected_completion_files(plan, intake, bundle)
    actual = {item.path: item for item in completion.retained_files}
    for path, record in expected.items():
        if actual.get(path) != record:
            raise CapabilityManifestError(
                f"V2 completion retained identity differs for {path}"
            )


