def _require_same_representation(value: Any) -> None:
    stage = getattr(value, "stage", None)
    if (
        value.representation
        != ARTICULATION_V2_STATIC_CONTROLLED_DISTANCE_REPRESENTATION
        or value.binding.representation
        != ARTICULATION_V2_STATIC_CONTROLLED_DISTANCE_REPRESENTATION
        or (
            stage is not None
            and stage.representation
            != ARTICULATION_V2_STATIC_CONTROLLED_DISTANCE_REPRESENTATION
        )
    ):
        raise ValueError("controlled-distance-v2 receipt mixes representations")


def _require_generated_file_matches_identities(
    generated_file: StaticReceiptFileV1,
    identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1,
) -> None:
    if (
        generated_file.path != identities.authorer.uri
        or generated_file.sha256 != identities.authorer.root_sha256
    ):
        raise ValueError("V2 generated file differs from dual URI/root identities")


