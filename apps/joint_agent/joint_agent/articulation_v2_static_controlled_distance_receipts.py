class ArticulationV2StaticControlledDistanceResultBundleV2(_ReceiptModel):
    schema_version: Literal[
        "joint-agent-articulation-v2-static-controlled-distance-result-bundle-v2"
    ]
    representation: Literal["prismatic_axial_interval_drive_body1_to_body0_v2"]
    adoption: ArticulationV2StaticControlledDistanceAdoptionReceiptV2
    authoring: ArticulationV2StaticControlledDistanceAuthoringReceiptV2
    readback: ArticulationV2StaticControlledDistanceReadbackReceiptV2
    gate3a: ArticulationV2StaticControlledDistanceGate3ClaimV2
    gate3b: ArticulationV2StaticControlledDistanceGate3ClaimV2

    @model_validator(mode="after")
    def _complete_chain(self) -> ArticulationV2StaticControlledDistanceResultBundleV2:
        receipts = (
            self.adoption,
            self.authoring,
            self.readback,
            self.gate3a,
            self.gate3b,
        )
        if any(item.representation != self.representation for item in receipts):
            raise ValueError("V2 result bundle mixes representations")
        if any(item.binding != self.adoption.binding for item in receipts[1:]):
            raise ValueError("V2 result bundle mixes evidence bindings")
        if tuple(item.stage.plan.stage for item in receipts) != (
            "contract",
            "authoring",
            "readback",
            "gate3a",
            "gate3b",
        ):
            raise ValueError("V2 result bundle stages are incomplete or substituted")
        if self.authoring.adoption_receipt_sha256 != controlled_distance_receipt_sha256(
            self.adoption
        ):
            raise ValueError("V2 authoring does not bind adoption")
        if self.readback.authoring_receipt_sha256 != controlled_distance_receipt_sha256(
            self.authoring
        ):
            raise ValueError("V2 readback does not bind authoring")
        readback_hash = controlled_distance_receipt_sha256(self.readback)
        if any(
            claim.readback_receipt_sha256 != readback_hash
            for claim in (self.gate3a, self.gate3b)
        ):
            raise ValueError("V2 Gate 3 claims do not bind readback")
        if any(item.status != "pass" for item in receipts[:3]):
            raise ValueError("V2 result bundle requires passing first three stages")
        if any(item.status == "error" for item in receipts[3:]):
            raise ValueError("V2 result bundle rejects Gate 3 execution errors")
        generated_file = self.authoring.generated_file
        generated = self.authoring.generated_identities
        if generated_file is None or generated is None:
            raise ValueError("V2 result bundle requires retained generated bytes")
        if any(
            item.generated_file != generated_file
            or item.generated_identities != generated
            for item in receipts[2:]
        ):
            raise ValueError("V2 downstream stages substitute generated bytes")
        return self


class ArticulationV2StaticControlledDistanceCompletionReceiptV2(_ReceiptModel):
    schema_version: Literal[
        "joint-agent-articulation-v2-static-controlled-distance-completion-v2"
    ]
    representation: Literal["prismatic_axial_interval_drive_body1_to_body0_v2"]
    binding: ArticulationV2StaticControlledDistanceEvidenceBindingV2
    evidence_paths: ArticulationV2StaticEvidencePathAllowlistV1
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    result_bundle: StaticReceiptFileV1
    retained_files: tuple[StaticReceiptFileV1, ...]
    terminal_receipt_path: Literal["completion.json"]
    dynamic_qualified: Literal[False]
    public_enabled: Literal[False]
    release_selection_applied: Literal[False]
    capability_manifest_updated: Literal[False]

    @field_validator("retained_files")
    @classmethod
    def _inventory(
        cls, value: tuple[StaticReceiptFileV1, ...]
    ) -> tuple[StaticReceiptFileV1, ...]:
        paths = tuple(item.path for item in value)
        if paths != tuple(sorted(paths)) or len(paths) != len(set(paths)):
            raise ValueError("V2 completion inventory must be sorted and unique")
        if STATIC_EVIDENCE_TERMINAL_RECEIPT_PATH in paths:
            raise ValueError("V2 completion cannot inventory itself")
        return value

    @model_validator(mode="after")
    def _exact_inventory(
        self,
    ) -> ArticulationV2StaticControlledDistanceCompletionReceiptV2:
        _require_same_representation(self)
        if self.terminal_receipt_path != self.evidence_paths.terminal_receipt:
            raise ValueError("V2 terminal path differs from evidence allowlist")
        if (
            tuple(item.path for item in self.retained_files)
            != self.evidence_paths.retained_paths
        ):
            raise ValueError("V2 completion inventory differs from evidence allowlist")
        by_path = {item.path: item for item in self.retained_files}
        _require_generated_file_matches_identities(
            self.generated_file, self.generated_identities
        )
        if by_path.get(self.generated_file.path) != self.generated_file:
            raise ValueError("V2 generated output is absent from completion inventory")
        if (
            self.result_bundle.path != STATIC_EVIDENCE_RESULT_BUNDLE_PATH
            or by_path.get(self.result_bundle.path) != self.result_bundle
        ):
            raise ValueError("V2 result bundle is absent from completion inventory")
        return self


