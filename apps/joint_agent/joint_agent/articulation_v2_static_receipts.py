def articulation_v2_static_comparison_checks(
    expected: ArticulationV2StaticJointSemanticsV1,
    observed: ArticulationV2StaticJointSemanticsV1,
) -> ArticulationV2StaticComparisonChecksV1:
    """Compare the complete normalized saved-stage semantics without I/O."""

    if (
        type(expected) is not ArticulationV2StaticJointSemanticsV1
        or type(observed) is not ArticulationV2StaticJointSemanticsV1
    ):
        raise TypeError("comparison inputs must use the exact static semantic model")
    return ArticulationV2StaticComparisonChecksV1(
        capability=expected.capability_id == observed.capability_id,
        selector=(
            expected.transform_version == observed.transform_version
            and expected.source_semantic_preimage_sha256
            == observed.source_semantic_preimage_sha256
            and expected.release_gate_asset_id == observed.release_gate_asset_id
            and expected.selector_type == observed.selector_type
            and expected.source_joint_path == observed.source_joint_path
            and expected.joint_id == observed.joint_id
            and expected.topology_decision == observed.topology_decision
            and expected.source_stage_default_prim == observed.source_stage_default_prim
            and expected.source_stage_meters_per_unit
            == observed.source_stage_meters_per_unit
            and expected.source_stage_up_axis == observed.source_stage_up_axis
            and expected.linear_unit_interpretation
            == observed.linear_unit_interpretation
            and expected.orientation_interpretation
            == observed.orientation_interpretation
        ),
        source_authority=expected.source_authority == observed.source_authority,
        endpoints=(
            expected.body0_link_id == observed.body0_link_id
            and expected.body1_link_id == observed.body1_link_id
            and expected.body0_prim_path == observed.body0_prim_path
            and expected.body1_prim_path == observed.body1_prim_path
        ),
        attachment_frames=expected.attachments == observed.attachments,
        constraint=expected.constraint == observed.constraint,
    )


_ModelT = TypeVar("_ModelT", bound=BaseModel)


def _canonical_model_bytes(value: _ModelT, model_type: type[_ModelT]) -> bytes:
    if type(value) is not model_type:
        raise TypeError(f"value must be an exact {model_type.__name__}")
    adapter = TypeAdapter(model_type)
    encoded = json.dumps(
        adapter.dump_python(value, mode="json"),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")
    validated = adapter.validate_json(encoded, strict=True)
    return json.dumps(
        adapter.dump_python(validated, mode="json"),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def canonical_articulation_v2_static_receipt_bytes(
    receipt: ArticulationV2StaticReceipt,
) -> bytes:
    allowed = (
        ArticulationV2StaticAdoptionReceiptV1,
        ArticulationV2StaticAuthoringReceiptV1,
        ArticulationV2StaticReadbackReceiptV1,
        ArticulationV2StaticGate3ClaimV1,
    )
    if type(receipt) not in allowed:
        raise TypeError("receipt must be an exact articulation-v2 static receipt")
    return _canonical_model_bytes(receipt, type(receipt))


