class ArticulationV2StaticReadbackReceiptV1(_ReceiptModel):
    """Dedicated substantive saved-stage comparison for fixed/distance output."""

    schema_version: Literal["joint-agent-articulation-v2-static-readback-v1"]
    binding: ArticulationV2StaticEvidenceBindingV1
    stage: ArticulationV2StaticReceiptStageV1
    status: Literal["pass", "fail"]
    authoring_receipt_sha256: str
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    expected: ArticulationV2StaticJointSemanticsV1
    observed: ArticulationV2StaticJointSemanticsV1
    checks: ArticulationV2StaticComparisonChecksV1

    @field_validator("authoring_receipt_sha256")
    @classmethod
    def _lowercase_sha256(cls, value: str) -> str:
        return _require_sha256(value, "authoring_receipt_sha256")

    @model_validator(mode="after")
    def _substantive_readback(self) -> ArticulationV2StaticReadbackReceiptV1:
        if self.stage.plan.stage != "readback":
            raise ValueError("readback receipt requires the readback stage")
        _require_generated_file_matches_identities(
            self.generated_file,
            self.generated_identities,
        )
        expected_checks = articulation_v2_static_comparison_checks(
            self.expected,
            self.observed,
        )
        if self.checks != expected_checks:
            raise ValueError("readback checks differ from substantive comparison")
        if expected_checks.passed != (self.expected == self.observed):
            raise ValueError("readback checks do not exhaust the semantic contract")
        expected_status = "pass" if expected_checks.passed else "fail"
        if self.status != expected_status:
            raise ValueError("readback status differs from substantive comparison")
        return self


class ArticulationV2StaticGate3ClaimV1(_ReceiptModel):
    """Retained Gate 3 claim; execution and closeout are owned elsewhere."""

    schema_version: Literal["joint-agent-articulation-v2-static-gate3-claim-v1"]
    binding: ArticulationV2StaticEvidenceBindingV1
    stage: ArticulationV2StaticReceiptStageV1
    status: ReceiptStatus
    readback_receipt_sha256: str
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    raw_report: StaticReceiptFileV1
    stdout_log: StaticReceiptFileV1
    stderr_log: StaticReceiptFileV1
    support_evidence: StaticReceiptFileV1 | None = None

    @field_validator("readback_receipt_sha256")
    @classmethod
    def _lowercase_sha256(cls, value: str) -> str:
        return _require_sha256(value, "readback_receipt_sha256")

    @model_validator(mode="after")
    def _gate3_stage(self) -> ArticulationV2StaticGate3ClaimV1:
        stage = self.stage.plan.stage
        if stage not in {"gate3a", "gate3b"}:
            raise ValueError("Gate 3 claim requires gate3a or gate3b stage")
        if self.raw_report.path != f"reports/{stage}.json":
            raise ValueError(f"{stage} raw report uses an unadmitted evidence path")
        if self.stdout_log.path != f"logs/{stage}.stdout.json":
            raise ValueError(f"{stage} stdout log uses an unadmitted evidence path")
        if self.stderr_log.path != f"logs/{stage}.stderr.json":
            raise ValueError(f"{stage} stderr log uses an unadmitted evidence path")
        if stage == "gate3a" and self.support_evidence is not None:
            raise ValueError("Gate 3A claim cannot carry Gate 3B support evidence")
        if stage == "gate3b" and (
            self.support_evidence is None
            or self.support_evidence.path != STATIC_EVIDENCE_GATE3B_SUPPORT_PATH
        ):
            raise ValueError("Gate 3B claim requires retained support evidence")
        _require_generated_file_matches_identities(
            self.generated_file,
            self.generated_identities,
        )
        return self


class ArticulationV2StaticResultBundleV1(_ReceiptModel):
    """Exact five-stage envelope consumed by later closeout and scoring."""

    schema_version: Literal["joint-agent-articulation-v2-static-result-bundle-v1"]
    adoption: ArticulationV2StaticAdoptionReceiptV1
    authoring: ArticulationV2StaticAuthoringReceiptV1
    readback: ArticulationV2StaticReadbackReceiptV1
    gate3a: ArticulationV2StaticGate3ClaimV1
    gate3b: ArticulationV2StaticGate3ClaimV1

    @model_validator(mode="after")
    def _one_identity_and_hash_chain(self) -> ArticulationV2StaticResultBundleV1:
        receipts = (
            self.adoption,
            self.authoring,
            self.readback,
            self.gate3a,
            self.gate3b,
        )
        if any(item.binding != self.adoption.binding for item in receipts[1:]):
            raise ValueError("all five stages must carry one evidence identity tuple")
        if tuple(item.stage.plan.stage for item in receipts) != (
            "contract",
            "authoring",
            "readback",
            "gate3a",
            "gate3b",
        ):
            raise ValueError("result bundle stages are incomplete or substituted")
        if self.authoring.adoption_receipt_sha256 != (
            articulation_v2_static_receipt_sha256(self.adoption)
        ):
            raise ValueError("authoring receipt does not bind the adoption receipt")
        if self.readback.authoring_receipt_sha256 != (
            articulation_v2_static_receipt_sha256(self.authoring)
        ):
            raise ValueError("readback receipt does not bind the authoring receipt")
        readback_sha256 = articulation_v2_static_receipt_sha256(self.readback)
        if any(
            claim.readback_receipt_sha256 != readback_sha256
            for claim in (self.gate3a, self.gate3b)
        ):
            raise ValueError("Gate 3 claims do not bind the readback receipt")
        if self.adoption.status != "pass" and self.authoring.status == "pass":
            raise ValueError("passing authoring requires passing contract adoption")
        if self.authoring.status != "pass" and self.readback.status == "pass":
            raise ValueError("passing readback requires passing authoring")
        if self.readback.status != "pass" and any(
            claim.status == "pass" for claim in (self.gate3a, self.gate3b)
        ):
            raise ValueError("passing Gate 3 requires passing saved-stage readback")
        if any(
            receipt.status != "pass"
            for receipt in (self.adoption, self.authoring, self.readback)
        ):
            raise ValueError(
                "complete result bundle requires passing contract, authoring, "
                "and readback stages"
            )
        if any(claim.status == "error" for claim in (self.gate3a, self.gate3b)):
            raise ValueError("complete result bundle rejects Gate 3 execution errors")
        generated = self.authoring.generated_identities
        generated_file = self.authoring.generated_file
        if generated is None or generated_file is None:
            raise ValueError("five-stage bundle requires retained authoring bytes")
        later = (self.readback, self.gate3a, self.gate3b)
        if any(
            item.generated_identities != generated
            or item.generated_file != generated_file
            for item in later
        ):
            raise ValueError(
                "readback and Gate 3 must reuse both authoring identity domains"
            )
        return self


class ArticulationV2StaticCompletionReceiptV1(_ReceiptModel):
    """Terminal inventory receipt for every allowed pre-completion file."""

    schema_version: Literal["joint-agent-articulation-v2-static-completion-v1"]
    binding: ArticulationV2StaticEvidenceBindingV1
    evidence_paths: ArticulationV2StaticEvidencePathAllowlistV1
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    result_bundle: StaticReceiptFileV1
    retained_files: tuple[StaticReceiptFileV1, ...]
    terminal_receipt_path: Literal["completion.json"]

    @field_validator("retained_files")
    @classmethod
    def _canonical_file_inventory(
        cls,
        value: tuple[StaticReceiptFileV1, ...],
    ) -> tuple[StaticReceiptFileV1, ...]:
        paths = tuple(item.path for item in value)
        if paths != tuple(sorted(paths)):
            raise ValueError("completion retained file inventory must be sorted")
        if len(paths) != len(set(paths)):
            raise ValueError("completion retained file paths must be unique")
        if STATIC_EVIDENCE_TERMINAL_RECEIPT_PATH in paths:
            raise ValueError("completion receipt cannot inventory itself")
        return value

    @model_validator(mode="after")
    def _exact_non_circular_inventory(
        self,
    ) -> ArticulationV2StaticCompletionReceiptV1:
        if self.terminal_receipt_path != self.evidence_paths.terminal_receipt:
            raise ValueError("completion terminal path differs from the allowlist")
        if tuple(item.path for item in self.retained_files) != (
            self.evidence_paths.retained_paths
        ):
            raise ValueError("completion inventory differs from evidence allowlist")
        by_path = {item.path: item for item in self.retained_files}
        _require_generated_file_matches_identities(
            self.generated_file,
            self.generated_identities,
        )
        if by_path.get(self.generated_file.path) != self.generated_file:
            raise ValueError("completion output identity is absent from inventory")
        if (
            self.result_bundle.path != STATIC_EVIDENCE_RESULT_BUNDLE_PATH
            or by_path.get(self.result_bundle.path) != self.result_bundle
        ):
            raise ValueError("completion result bundle is absent from inventory")
        return self


class ArticulationV2StaticGate3FailureReceiptV1(_ReceiptModel):
    """Terminal, non-qualifying receipt for a missing Gate 3 report."""

    schema_version: Literal["joint-agent-articulation-v2-static-gate3-failure-v1"]
    binding: ArticulationV2StaticEvidenceBindingV1
    stage: ArticulationV2StaticReceiptStageV1
    status: Literal["error"]
    failure_code: Literal[
        "articulation_v2_static_gate3a_report_missing_after_exit",
        "articulation_v2_static_gate3b_report_missing_after_exit",
    ]
    failure_detail: str
    report_observation: Literal["missing"]
    expected_report_path: Literal["reports/gate3a.json", "reports/gate3b.json"]
    returncode: int = Field(ge=-255, le=255)
    termination_reason: Literal[
        "exited",
        "outer_deadline_exceeded",
        "output_limit_exceeded",
        "containment_failure",
    ]
    generated_file: StaticReceiptFileV1
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1
    stdout_log: StaticReceiptFileV1
    stderr_log: StaticReceiptFileV1
    retained_files: tuple[StaticReceiptFileV1, ...]
    terminal_receipt_path: Literal["failure.json"]
    static_qualified: Literal[False]
    dynamic_qualified: Literal[False]
    public_enabled: Literal[False]
    release_selection_applied: Literal[False]
    capability_manifest_updated: Literal[False]

    @field_validator("failure_detail")
    @classmethod
    def _bounded_failure_detail(cls, value: str) -> str:
        if not value or len(value) > 4096 or "\x00" in value:
            raise ValueError("Gate 3 failure detail must be nonempty and bounded")
        return value

    @field_validator("retained_files")
    @classmethod
    def _canonical_failure_inventory(
        cls,
        value: tuple[StaticReceiptFileV1, ...],
    ) -> tuple[StaticReceiptFileV1, ...]:
        paths = tuple(item.path for item in value)
        if paths != tuple(sorted(paths)) or len(paths) != len(set(paths)):
            raise ValueError("Gate 3 failure inventory must be sorted and unique")
        if STATIC_EVIDENCE_GATE3_FAILURE_RECEIPT_PATH in paths:
            raise ValueError("Gate 3 failure receipt cannot inventory itself")
        return value

    @model_validator(mode="after")
    def _exact_gate3_failure(self) -> ArticulationV2StaticGate3FailureReceiptV1:
        stage = self.stage.plan.stage
        if stage not in {"gate3a", "gate3b"}:
            raise ValueError("Gate 3 failure receipt requires a Gate 3 stage")
        _require_generated_file_matches_identities(
            self.generated_file,
            self.generated_identities,
        )
        expected_code = f"articulation_v2_static_{stage}_report_missing_after_exit"
        expected_report = f"reports/{stage}.json"
        expected_stdout = f"logs/{stage}.stdout.json"
        expected_stderr = f"logs/{stage}.stderr.json"
        if self.failure_code != expected_code:
            raise ValueError("Gate 3 failure code differs from its stage")
        if self.expected_report_path != expected_report:
            raise ValueError("Gate 3 expected report differs from its stage")
        if self.stdout_log.path != expected_stdout:
            raise ValueError("Gate 3 failure stdout uses an unadmitted path")
        if self.stderr_log.path != expected_stderr:
            raise ValueError("Gate 3 failure stderr uses an unadmitted path")
        path_builder = (
            articulation_v2_static_gate3a_failure_paths
            if stage == "gate3a"
            else articulation_v2_static_gate3b_failure_paths
        )
        expected_paths = path_builder(
            constraint_kind=self.binding.run.selector.constraint_kind,
            generated_output=self.generated_file.path,
        )
        retained_paths = tuple(
            path
            for path in expected_paths
            if path != STATIC_EVIDENCE_GATE3_FAILURE_RECEIPT_PATH
        )
        if tuple(item.path for item in self.retained_files) != retained_paths:
            raise ValueError("Gate 3 failure inventory differs from the contract")
        by_path = {item.path: item for item in self.retained_files}
        if by_path.get(self.generated_file.path) != self.generated_file:
            raise ValueError("Gate 3 failure output identity is absent from inventory")
        if by_path.get(self.stdout_log.path) != self.stdout_log:
            raise ValueError("Gate 3 failure stdout identity is absent from inventory")
        if by_path.get(self.stderr_log.path) != self.stderr_log:
            raise ValueError("Gate 3 failure stderr identity is absent from inventory")
        return self


