class StaticReceiptFileV1(_ReceiptModel):
    """Exact retained file identity, with no file access behavior."""

    path: str
    size_bytes: int = Field(gt=0)
    sha256: str

    @field_validator("path")
    @classmethod
    def _canonical_path(cls, value: str) -> str:
        try:
            canonical: str = validated_artifact_relative_key(value)
        except ValueError as exc:
            raise ValueError("receipt path must be canonical and relative") from exc
        return canonical

    @field_validator("sha256")
    @classmethod
    def _lowercase_sha256(cls, value: str) -> str:
        return _require_sha256(value, "receipt file sha256")


