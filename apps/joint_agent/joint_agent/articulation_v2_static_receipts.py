def canonical_articulation_v2_static_gate3_closeout_bytes(
    plan: ArticulationV2StaticRunPlanV1,
    intake: ArticulationV2StaticIntakeV1,
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1,
) -> bytes:
    """Derive the exact retained Gate 3 closeout input from receipt identities."""

    if type(plan) is not ArticulationV2StaticRunPlanV1:
        raise TypeError("Gate 3 closeout plan must use the exact static run plan")
    if type(intake) is not ArticulationV2StaticIntakeV1:
        raise TypeError("Gate 3 closeout intake must use the exact static intake")
    if (
        type(generated_identities)
        is not ArticulationV2StaticGeneratedArtifactIdentitiesV1
    ):
        raise TypeError(
            "Gate 3 closeout identities must use the exact generated identity model"
        )
    gate3 = generated_identities.gate3
    document = {
        "schema_version": ARTICULATION_V2_STATIC_GATE3_CLOSEOUT_SCHEMA_VERSION,
        "run_id": plan.run.run_id,
        "run_plan_sha256": articulation_v2_static_run_plan_sha256(plan),
        "intake_sha256": articulation_v2_static_intake_sha256(intake),
        "generated_artifact": {
            "uri": gate3.uri,
            "root_sha256": gate3.root_sha256,
            "dependency_bundle_schema_version": gate3.dependency_bundle_schema_version,
            "dependency_bundle_sha256": gate3.dependency_bundle_sha256,
            "dependency_bundle_entry_count": gate3.dependency_bundle_entry_count,
        },
        "assets": [
            {
                "asset_id": plan.run.selector.release_gate_asset_id,
                "generated_usd_path": plan.output.output_key,
            }
        ],
    }
    return json.dumps(
        document,
        allow_nan=False,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


