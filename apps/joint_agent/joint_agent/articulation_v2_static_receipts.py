class ArticulationV2StaticAuthoringReceiptV1(_ReceiptModel):
    """Dedicated 0.6 receipt for retained authoring output, when present."""

    schema_version: Literal["joint-agent-articulation-v2-static-authoring-v1"]
    binding: ArticulationV2StaticEvidenceBindingV1
    stage: ArticulationV2StaticReceiptStageV1
    status: ReceiptStatus
    adoption_receipt_sha256: str
    authoring_result: StaticReceiptFileV1
    generated_file: StaticReceiptFileV1 | None = None
    generated_identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1 | None = (
        None
    )

    @field_validator("adoption_receipt_sha256")
    @classmethod
    def _lowercase_sha256(cls, value: str) -> str:
        return _require_sha256(value, "adoption_receipt_sha256")

    @model_validator(mode="after")
    def _authoring_stage_and_optional_bytes(
        self,
    ) -> ArticulationV2StaticAuthoringReceiptV1:
        if self.stage.plan.stage != "authoring":
            raise ValueError("authoring receipt requires the authoring stage")
        if self.authoring_result.path != STATIC_EVIDENCE_AUTHORING_RESULT_PATH:
            raise ValueError("authoring result uses an unadmitted evidence path")
        if (self.generated_file is None) != (self.generated_identities is None):
            raise ValueError(
                "generated file and dual identities must appear only together"
            )
        if self.status == "pass" and self.generated_identities is None:
            raise ValueError("passing authoring requires retained generated bytes")
        if self.generated_file is not None and self.generated_identities is not None:
            _require_generated_file_matches_identities(
                self.generated_file,
                self.generated_identities,
            )
        return self


