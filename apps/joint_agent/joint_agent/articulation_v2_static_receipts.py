def validate_articulation_v2_static_result_bundle(
    loaded: LoadedCapabilityManifest,
    plan: ArticulationV2StaticRunPlanV1,
    intake: ArticulationV2StaticIntakeV1,
    bundle: ArticulationV2StaticResultBundleV1,
) -> None:
    """Cross-check a five-stage bundle without filesystem or subprocess work."""

    plan = _revalidate_articulation_v2_static_run_plan(plan)
    intake = _revalidate_articulation_v2_static_intake(intake)
    bundle = _revalidate_articulation_v2_static_result_bundle(bundle)
    validate_articulation_v2_static_intake(loaded, plan, intake)
    expected_binding = _evidence_binding(plan, intake)
    receipts: tuple[ArticulationV2StaticReceipt, ...] = (
        bundle.adoption,
        bundle.authoring,
        bundle.readback,
        bundle.gate3a,
        bundle.gate3b,
    )
    if any(item.binding != expected_binding for item in receipts):
        raise CapabilityManifestError(
            "static result bundle substitutes a run-plan, intake, or source identity"
        )
    for receipt, expected_stage in zip(
        receipts,
        plan.stages.ordered(),
        strict=True,
    ):
        if receipt.stage.plan != expected_stage:
            raise CapabilityManifestError(
                f"static result bundle substitutes the {expected_stage.stage} stage"
            )
    if (
        bundle.adoption.contract_file.path != intake.contract_uri
        or bundle.adoption.contract_file.sha256 != intake.contract_sha256
        or bundle.adoption.contract_file.size_bytes != intake.contract_size_bytes
        or bundle.adoption.selector_semantics_sha256
        != intake.run.selector.expected_joint_semantics_sha256
    ):
        raise CapabilityManifestError(
            "static adoption receipt differs from the exact intake contract"
        )
    if bundle.readback.expected != intake.contract_semantics:
        raise CapabilityManifestError(
            "static readback expected semantics differ from the intake"
        )
    generated = bundle.authoring.generated_identities
    if generated is None or generated.authorer.uri != plan.output.output_key:
        raise CapabilityManifestError(
            "static authoring receipt differs from the planned output locator"
        )


def validate_articulation_v2_static_completion_receipt(
    loaded: LoadedCapabilityManifest,
    plan: ArticulationV2StaticRunPlanV1,
    intake: ArticulationV2StaticIntakeV1,
    bundle: ArticulationV2StaticResultBundleV1,
    completion: ArticulationV2StaticCompletionReceiptV1,
) -> None:
    """Validate the terminal inventory entirely from retained identities."""

    plan = _revalidate_articulation_v2_static_run_plan(plan)
    intake = _revalidate_articulation_v2_static_intake(intake)
    bundle = _revalidate_articulation_v2_static_result_bundle(bundle)
    completion = _revalidate_articulation_v2_static_completion(completion)
    validate_articulation_v2_static_result_bundle(loaded, plan, intake, bundle)
    expected_binding = _evidence_binding(plan, intake)
    if completion.binding != expected_binding:
        raise CapabilityManifestError("static completion substitutes run identity")
    if completion.evidence_paths != plan.evidence_paths:
        raise CapabilityManifestError("static completion substitutes evidence paths")
    if completion.generated_identities != bundle.authoring.generated_identities:
        raise CapabilityManifestError(
            "static completion substitutes generated identity domains"
        )
    if completion.generated_file != bundle.authoring.generated_file:
        raise CapabilityManifestError("static completion substitutes generated bytes")

    expected_files = _expected_completion_files(plan, intake, bundle)
    actual_files = {item.path: item for item in completion.retained_files}
    for path, expected in expected_files.items():
        if actual_files.get(path) != expected:
            raise CapabilityManifestError(
                f"static completion retained identity differs for {path}"
            )


def _revalidate_articulation_v2_static_result_bundle(
    bundle: ArticulationV2StaticResultBundleV1,
) -> ArticulationV2StaticResultBundleV1:
    if type(bundle) is not ArticulationV2StaticResultBundleV1:
        raise CapabilityManifestError(
            "articulation-v2 static results require the exact 0.6 bundle contract"
        )
    try:
        return TypeAdapter(ArticulationV2StaticResultBundleV1).validate_json(
            canonical_articulation_v2_static_result_bundle_bytes(bundle),
            strict=True,
        )
    except (TypeError, ValueError) as exc:
        raise CapabilityManifestError(
            "articulation-v2 static result bundle fails strict invariant revalidation"
        ) from exc


