def _expected_completion_files(
    plan: ArticulationV2StaticRunPlanV1,
    intake: ArticulationV2StaticIntakeV1,
    bundle: ArticulationV2StaticResultBundleV1,
) -> dict[str, StaticReceiptFileV1]:
    authoring = bundle.authoring
    generated_file = authoring.generated_file
    generated_identities = authoring.generated_identities
    support_evidence = bundle.gate3b.support_evidence
    if generated_file is None or generated_identities is None:
        raise CapabilityManifestError("static completion has no generated bytes")
    if support_evidence is None:
        raise CapabilityManifestError("static completion has no Gate 3B support")
    files = {
        STATIC_EVIDENCE_RUN_PLAN_PATH: _model_file(
            STATIC_EVIDENCE_RUN_PLAN_PATH,
            canonical_articulation_v2_static_run_plan_bytes(plan),
        ),
        STATIC_EVIDENCE_INTAKE_PATH: StaticReceiptFileV1(
            path=STATIC_EVIDENCE_INTAKE_PATH,
            size_bytes=len(canonical_articulation_v2_static_intake_bytes(intake)),
            sha256=articulation_v2_static_intake_sha256(intake),
        ),
        STATIC_EVIDENCE_GATE3_CLOSEOUT_PATH: _model_file(
            STATIC_EVIDENCE_GATE3_CLOSEOUT_PATH,
            canonical_articulation_v2_static_gate3_closeout_bytes(
                plan,
                intake,
                generated_identities,
            ),
        ),
        intake.contract_uri: bundle.adoption.contract_file,
        STATIC_EVIDENCE_AUTHORING_RESULT_PATH: authoring.authoring_result,
        generated_file.path: generated_file,
        "receipts/contract.json": _model_file(
            "receipts/contract.json",
            canonical_articulation_v2_static_receipt_bytes(bundle.adoption),
        ),
        "receipts/authoring.json": _model_file(
            "receipts/authoring.json",
            canonical_articulation_v2_static_receipt_bytes(bundle.authoring),
        ),
        "receipts/readback.json": _model_file(
            "receipts/readback.json",
            canonical_articulation_v2_static_receipt_bytes(bundle.readback),
        ),
        "claims/gate3a.json": _model_file(
            "claims/gate3a.json",
            canonical_articulation_v2_static_receipt_bytes(bundle.gate3a),
        ),
        "claims/gate3b.json": _model_file(
            "claims/gate3b.json",
            canonical_articulation_v2_static_receipt_bytes(bundle.gate3b),
        ),
        bundle.gate3a.raw_report.path: bundle.gate3a.raw_report,
        bundle.gate3b.raw_report.path: bundle.gate3b.raw_report,
        bundle.gate3a.stdout_log.path: bundle.gate3a.stdout_log,
        bundle.gate3a.stderr_log.path: bundle.gate3a.stderr_log,
        bundle.gate3b.stdout_log.path: bundle.gate3b.stdout_log,
        bundle.gate3b.stderr_log.path: bundle.gate3b.stderr_log,
        STATIC_EVIDENCE_GATE3B_SUPPORT_PATH: support_evidence,
        STATIC_EVIDENCE_RESULT_BUNDLE_PATH: _model_file(
            STATIC_EVIDENCE_RESULT_BUNDLE_PATH,
            canonical_articulation_v2_static_result_bundle_bytes(bundle),
        ),
    }
    return files


def _model_file(path: str, payload: bytes) -> StaticReceiptFileV1:
    return StaticReceiptFileV1(
        path=path,
        size_bytes=len(payload),
        sha256=hashlib.sha256(payload).hexdigest(),
    )


def _evidence_binding(
    plan: ArticulationV2StaticRunPlanV1,
    intake: ArticulationV2StaticIntakeV1,
) -> ArticulationV2StaticEvidenceBindingV1:
    return ArticulationV2StaticEvidenceBindingV1(
        run_plan_sha256=articulation_v2_static_run_plan_sha256(plan),
        intake_sha256=articulation_v2_static_intake_sha256(intake),
        run=plan.run,
    )


def _require_generated_file_matches_identities(
    generated_file: StaticReceiptFileV1,
    identities: ArticulationV2StaticGeneratedArtifactIdentitiesV1,
) -> None:
    if generated_file.size_bytes <= 0:
        raise ValueError("generated artifact must retain nonempty bytes")
    if (
        generated_file.path != identities.authorer.uri
        or generated_file.sha256 != identities.authorer.root_sha256
    ):
        raise ValueError("generated file differs from dual URI/root identities")


def _require_sha256(value: str, label: str) -> str:
    if _SHA256_RE.fullmatch(value) is None:
        raise ValueError(f"{label} must be a lowercase SHA-256")
    return value


