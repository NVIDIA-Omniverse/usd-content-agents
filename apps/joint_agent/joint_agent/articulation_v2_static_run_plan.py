"""Deterministic, non-executing run-plan contracts for Joint 0.6.

The plan selects one exact #1012 admission and its admitted #1025 selector
lineage. It names a provider-neutral source request, reviewed command
identities, one fresh output locator, and the complete evidence-path allowlist.
Generated bytes and generated hashes do not exist at this boundary.
"""

