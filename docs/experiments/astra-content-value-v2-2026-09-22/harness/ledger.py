"""Controller-only transactional lane and model-request ledger.

There is ONE database on the controller, never one independent global cap per
worker. A crashed/uncertain worker keeps its lane occupied until explicitly reaped.
No secrets, prompts, model reasoning, or response content are stored here.
"""
from __future__ import annotations

import json
import sqlite3
import time
import uuid
from contextlib import contextmanager

from common import EFFORT, MODEL, canonical, identifier, object_hash, require
from request_identity import project


class Ledger:
    def __init__(self, path):
        self.db = sqlite3.connect(path, timeout=30, isolation_level=None)
        self.db.row_factory = sqlite3.Row
        self.db.execute("PRAGMA journal_mode=WAL")
        self.db.executescript("""
        CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS lanes(id TEXT PRIMARY KEY, definition TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS runs(
          id TEXT PRIMARY KEY, lane TEXT NOT NULL, arm TEXT NOT NULL, lease TEXT UNIQUE NOT NULL,
          spec_sha TEXT NOT NULL, started REAL NOT NULL, deadline REAL NOT NULL,
          status TEXT NOT NULL, reap_sha TEXT, cancelled INTEGER NOT NULL DEFAULT 0);
        CREATE UNIQUE INDEX IF NOT EXISTS one_active_lane ON runs(lane) WHERE status!='reaped';
        CREATE TABLE IF NOT EXISTS requests(
          id TEXT PRIMARY KEY, run TEXT NOT NULL, request_sha TEXT NOT NULL,
          started REAL NOT NULL, finished REAL, status TEXT NOT NULL,
          response_id TEXT UNIQUE, usage TEXT, detail TEXT,
          model TEXT, effort TEXT, requested_tier TEXT, response_tier TEXT,
          request_identity TEXT, downstream_disconnected INTEGER);
        CREATE TABLE IF NOT EXISTS candidates(
          run TEXT NOT NULL, ordinal INTEGER NOT NULL, manifest_sha TEXT NOT NULL,
          created REAL NOT NULL, PRIMARY KEY(run,ordinal));
        """)
        # Historical ledgers remain readable without a schema migration. A
        # fresh database is required for prospective identity-gated requests.

    @contextmanager
    def transaction(self):
        self.db.execute("BEGIN IMMEDIATE")
        try:
            yield
            self.db.execute("COMMIT")
        except BaseException:
            self.db.execute("ROLLBACK")
            raise

    def configure(self, protocol):
        with self.transaction():
            old = self.db.execute("SELECT value FROM settings WHERE key='protocol'").fetchone()
            value = canonical(protocol).decode()
            require(not old or old[0] == value, "Controller already bound to a different protocol")
            self.db.execute("INSERT OR IGNORE INTO settings VALUES('protocol',?)", (value,))
            for lane in protocol["lanes"]:
                self.db.execute("INSERT OR IGNORE INTO lanes VALUES(?,?)", (lane["id"], canonical(lane).decode()))

    def acquire(self, spec, wall_seconds, *, now=None):
        now = time.time() if now is None else now
        identifier(spec["run_id"])
        with self.transaction():
            require(self.db.execute("SELECT 1 FROM lanes WHERE id=?", (spec["lane_id"],)).fetchone(), "Unknown lane")
            require(not self.db.execute("SELECT 1 FROM runs WHERE id=?", (spec["run_id"],)).fetchone(), "Run ID was already used; no resume")
            lease = uuid.uuid4().hex
            self.db.execute("INSERT INTO runs(id,lane,arm,lease,spec_sha,started,deadline,status) VALUES(?,?,?,?,?,?,?,'reserved')",
                            (spec["run_id"], spec["lane_id"], spec["arm"], lease, object_hash(spec), now, now + wall_seconds))
            return lease

    def start(self, run, lease, *, now=None, wall_seconds=None):
        now = time.time() if now is None else now
        with self.transaction():
            row = self.db.execute("SELECT * FROM runs WHERE id=? AND lease=?", (run, lease)).fetchone()
            require(row is not None and row["status"] == "reserved", "Lease is not reserved")
            protocol = json.loads(self.db.execute("SELECT value FROM settings WHERE key='protocol'").fetchone()[0])
            wall = protocol["wall_seconds"]
            require(wall_seconds is None or wall_seconds == wall, "Budget override forbidden")
            self.db.execute("UPDATE runs SET status='running',started=?,deadline=? WHERE id=?", (now, now + wall, run))

    def cancel(self, run):
        self.db.execute("UPDATE runs SET cancelled=1 WHERE id=?", (run,))

    def reap(self, run, lease, receipt):
        # A signed/trusted worker supervisor supplies this receipt. It cannot be
        # generated by the author and must cover its exact lease/container.
        require(receipt.get("run_id") == run and receipt.get("lease") == lease, "Wrong reap binding")
        require(receipt.get("cgroup_populated") == 0 and receipt.get("namespace_init_exited") is True,
                "A deadline or lost SSH connection does not prove the worker is reaped")
        with self.transaction():
            row = self.db.execute("SELECT * FROM runs WHERE id=? AND lease=?", (run, lease)).fetchone()
            require(row is not None, "Unknown lease")
            digest = object_hash(receipt)
            require(row["reap_sha"] in (None, digest), "Conflicting reap receipt")
            self.db.execute("UPDATE runs SET status='reaped',reap_sha=? WHERE id=?", (digest, run))

    def begin_request(self, run, body, *, now=None):
        now = time.time() if now is None else now
        identity = project(body)
        columns = {row[1] for row in self.db.execute('PRAGMA table_info(requests)')}
        require({'request_identity', 'downstream_disconnected'} <= columns,
                'Legacy ledger cannot admit new requests; create a fresh run database')
        require(body.get("model") == MODEL, "Only Astra is allowed")
        protocol = json.loads(self.db.execute("SELECT value FROM settings WHERE key='protocol'").fetchone()[0])
        require(protocol.get("reasoning_effort") == EFFORT and protocol.get("wire_reasoning_effort") == "xhigh",
                "Missing trusted UI-to-wire mapping")
        require(isinstance(body.get("reasoning"), dict) and body["reasoning"].get("effort") == protocol["wire_reasoning_effort"],
                "Responses effort differs from the qualified Astra Ultra resolution; request is not rewritten")
        require(not any(key in body for key in ("conversation", "thread_id", "session_id", "background")), "External context/background calls are forbidden")
        tier = body.get("service_tier")
        require(tier in (None, "auto", "default", "priority", "flex", "scale", "batch"), "Unrecognized service tier")
        def no_external_references(value):
            if isinstance(value, dict):
                require(value.get("type") != "item_reference" and not any(k in value for k in ("file_id", "vector_store_ids", "container_id")), "External stored input reference forbidden")
                if "image_url" in value:
                    require(isinstance(value["image_url"], str) and value["image_url"].startswith("data:image/"), "Only inline image inputs are qualified")
                for nested in value.values():
                    no_external_references(nested)
            elif isinstance(value, list):
                for nested in value:
                    no_external_references(nested)
        no_external_references(body.get("input"))
        # Remote MCP/computer containers could escape this worker's data boundary.
        require(all(t.get("type") in ("function", "custom") for t in body.get("tools", [])), "Server-side tools are not qualified")
        with self.transaction():
            row = self.db.execute("SELECT * FROM runs WHERE id=?", (run,)).fetchone()
            require(row is not None and row["status"] == "running" and not row["cancelled"] and now < row["deadline"], "Run is not active or budget expired")
            prior = body.get("previous_response_id")
            if prior:
                owned = self.db.execute("SELECT 1 FROM requests WHERE run=? AND response_id=? AND status='completed'", (run, prior)).fetchone()
                require(owned, "Previous response is not an owned completed response")
            request_id = uuid.uuid4().hex
            self.db.execute("INSERT INTO requests(id,run,request_sha,started,status,model,effort,requested_tier,request_identity) VALUES(?,?,?,?,'pending',?,?,?,?)",
                            (request_id, run, object_hash(body), now, body["model"], body["reasoning"]["effort"], tier, canonical(identity).decode()))
            return request_id

    def record_relay(self, request_id, disconnected):
        require(type(disconnected) is bool, 'Relay disconnect flag must be boolean')
        self.db.execute('UPDATE requests SET downstream_disconnected=? WHERE id=?', (int(disconnected), request_id))

    def finish_request(self, request_id, response, *, now=None):
        now = time.time() if now is None else now
        require(response.get("model", MODEL) == MODEL, "Upstream returned another model")
        require(isinstance(response.get("id"), str) and response["id"], "Missing response ID")
        usage = response.get("usage")
        require(isinstance(usage, dict), "Missing authoritative terminal usage")
        for key in ("input_tokens", "output_tokens", "total_tokens"):
            require(type(usage.get(key)) is int and usage[key] >= 0, f"Invalid {key}")
        require(usage["total_tokens"] == usage["input_tokens"] + usage["output_tokens"], "Inconsistent token totals")
        for key, parent, limit in (("cached_tokens", "input_tokens_details", "input_tokens"), ("reasoning_tokens", "output_tokens_details", "output_tokens")):
            value = usage.get(parent, {}).get(key, 0)
            require(type(value) is int and 0 <= value <= usage[limit], "Invalid usage detail")
        status = response.get("status")
        require(status in ("completed", "failed", "incomplete", "cancelled"), "Nonterminal response")
        response_tier = response.get("service_tier")
        require(response_tier in (None, "auto", "default", "priority", "flex", "scale", "batch"), "Unrecognized response service tier")
        with self.transaction():
            old = self.db.execute("SELECT * FROM requests WHERE id=?", (request_id,)).fetchone()
            require(old is not None, "Unrecognized request")
            serialized = canonical(usage).decode()
            if old["status"] != "pending":
                require(old["response_id"] == response["id"] and old["usage"] == serialized and old["status"] == status, "Conflicting terminal usage")
                return
            self.db.execute("UPDATE requests SET finished=?,status=?,response_id=?,usage=?,response_tier=? WHERE id=?",
                            (now, status, response["id"], serialized, response_tier, request_id))

    def failed_transport(self, request_id, detail):
        # Failure is retained but is NEVER converted to zero usage or complete.
        self.db.execute("UPDATE requests SET detail=? WHERE id=? AND status='pending'", (str(detail)[:200], request_id))

    def checkpoint(self, run, manifest_sha, *, now=None):
        now = time.time() if now is None else now
        with self.transaction():
            row = self.db.execute("SELECT * FROM runs WHERE id=?", (run,)).fetchone()
            require(row and row["status"] == "running" and not row["cancelled"] and now < row["deadline"], "Run unavailable")
            count = self.db.execute("SELECT COUNT(*) FROM candidates WHERE run=?", (run,)).fetchone()[0]
            self.db.execute("INSERT INTO candidates VALUES(?,?,?,?)", (run, count, manifest_sha, now))
            return count

    def usage(self, run):
        rows = list(self.db.execute("SELECT * FROM requests WHERE run=? ORDER BY started,id", (run,)))
        protocol = json.loads(self.db.execute("SELECT value FROM settings WHERE key='protocol'").fetchone()[0])
        deadline = self.db.execute("SELECT deadline FROM runs WHERE id=?", (run,)).fetchone()[0]
        totals = dict(input_tokens=0, cached_input_tokens=0, output_tokens=0, reasoning_output_tokens=0, total_tokens=0)
        for r in rows:
            if not r["usage"]:
                continue
            u = json.loads(r["usage"])
            for key in ("input_tokens", "output_tokens", "total_tokens"):
                totals[key] += u[key]
            totals["cached_input_tokens"] += u.get("input_tokens_details", {}).get("cached_tokens", 0)
            totals["reasoning_output_tokens"] += u.get("output_tokens_details", {}).get("reasoning_tokens", 0)
        return {"schema_version": "model-ledger.v2", "run_id": run, "complete": bool(rows) and all(r["usage"] is not None for r in rows),
                "within_deadline": bool(rows) and all(r["finished"] is not None and r["finished"] <= deadline for r in rows),
                "request_count": len(rows), "terminal_count": sum(r["usage"] is not None for r in rows), "totals": totals,
                "requested_ui_effort": protocol["reasoning_effort"], "resolved_wire_effort": protocol["wire_reasoning_effort"],
                "reasoning_mapping_sha256": protocol.get("reasoning_mapping_sha256"), "model_catalog_sha256": protocol.get("model_catalog_sha256"),
                "ui_effort_verification": "Primary and every child CLI must be audited as ultra; wire xhigh alone does not establish Ultra mode.",
                "requests": [{**{k: r[k] for k in ("id", "request_sha", "started", "finished", "status", "response_id", "detail", "model", "requested_tier", "response_tier")},
                              "wire_reasoning_effort": r["effort"],
                              "request_identity": json.loads(r['request_identity']) if 'request_identity' in r.keys() and r['request_identity'] else None,
                              "downstream_disconnected": bool(r['downstream_disconnected']) if 'downstream_disconnected' in r.keys() and r['downstream_disconnected'] is not None else None,
                              "usage": json.loads(r["usage"]) if r["usage"] else None} for r in rows],
                "scope": "All requests through the enforced run-scoped model route, including children. Client ledger, not invoice. No missing request is counted as zero."}
